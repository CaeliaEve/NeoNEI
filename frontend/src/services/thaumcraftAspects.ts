export function normalizeAspectName(name: string): string {
  const hashName = resolveThaumcraftAspectNameFromHash(extractThaumcraftAspectHash(name));
  if (hashName) return hashName;

  const trimmed = name
    .trim()
    .replace(/^(?:要素|源质|瑕佺礌|婧愯川|aspect|aspects|essentia)\s*[:：]\s*/i, '')
    .trim();
  if (!trimmed) return 'Unknown';

  const lowered = trimmed.toLowerCase();
  const mapped = ASPECT_NAME_MAP[lowered] || ASPECT_NAME_MAP[trimmed];
  if (mapped) return mapped;

  // For raw aspect keys not yet in the dictionary, prefer readable title-case over Unknown.
  if (/^[a-z][a-z0-9_]*$/i.test(trimmed)) {
    return trimmed.charAt(0).toUpperCase() + trimmed.slice(1);
  }

  return trimmed;
}

export function getThaumcraftAspectTexturePath(
  aspect: { name?: string | null; hash?: string | null; itemId?: string | null; imageFileName?: string | null } | string | null | undefined,
): string | null {
  const candidates =
    typeof aspect === 'string'
      ? [aspect]
      : [
          aspect?.name || null,
          aspect?.itemId || null,
          aspect?.imageFileName || null,
          aspect?.hash ? resolveThaumcraftAspectNameFromHash(aspect.hash) || null : null,
        ];

  for (const rawName of candidates) {
    if (!rawName) continue;
    const normalized = normalizeAspectName(rawName);
    if (!normalized || normalized === 'Unknown') continue;

    const textureName = ASPECT_TEXTURE_NAME_ALIASES[normalized.toLowerCase()] || normalized.toLowerCase();
    if (NATIVE_ASPECT_TEXTURE_NAMES.has(textureName)) {
      return `/textures/thaumcraft-aspects-exported/${textureName}.gif`;
    }
  }

  return null;
}

export function parseAspectNameFromLocalized(localizedName?: string): string | null {
  if (!localizedName) return null;

  const zh = localizedName.match(/(?:要素|源质|瑕佺礌|婧愯川)\s*[:：]\s*(.+)$/);
  if (zh) {
    return normalizeAspectName(zh[1]);
  }

  const en = localizedName.match(/(?:aspects?|essentia)\s*[:：]\s*(.+)$/i);
  if (en) {
    return normalizeAspectName(en[1]);
  }

  return null;
}
