import {test,expect} from '@playwright/test';

test('Compiler native reference fixture preserves mob rules, search, deep links and item navigation',async({page,request},testInfo)=>{
  test.skip(process.env.NEONEI_TEST_NATIVE_REFERENCES!=='1','Requires the actual Compiler native-reference fixture');
  const manifest=await(await request.get('/api/catalog')).json();
  const errors:string[]=[];page.on('pageerror',error=>errors.push(error.message));
  await page.goto('/mobs?catalog='+manifest.id);
  await expect(page.getByRole('heading',{name:'生物与掉落',exact:true})).toBeVisible();
  await expect(page.locator('.mob-card')).toHaveCount(1);
  await page.getByRole('searchbox',{name:'查找生物'}).fill('missing');
  await page.getByRole('button',{name:'搜索',exact:true}).click();
  await expect(page.locator('.mob-page')).toContainText('没有符合筛选条件');
  await page.getByRole('searchbox',{name:'查找生物'}).fill('Native fixture');
  await page.getByRole('button',{name:'搜索',exact:true}).click();
  await page.getByRole('link',{name:'Native fixture mob',exact:true}).click();
  await expect(page.locator('.drop-card')).toHaveCount(1);
  await expect(page.locator('.drop-card')).toContainText('数量 3');
  await expect(page.locator('.drop-card')).toContainText('12500 / 10000');
  await expect(page.locator('.drop-card')).toContainText('仅玩家击杀');
  await expect(page.locator('.drop-card')).toContainText('附魔强度 30');
  await expect(page.locator('.drop-card')).toContainText('Native conditional note');
  await page.getByText('随机损伤',{exact:true}).click();
  await expect(page.locator('.drop-card')).toContainText('元数据 7：权重 5');
  await page.screenshot({path:testInfo.outputPath('mob-drops.png'),fullPage:true});
  await page.reload();await expect(page.locator('.drop-card')).toHaveCount(1);
  await page.locator('.drop-card .item-link').click({button:'right'});
  await expect(page).toHaveURL(/\/recipe\/item_.*tab=usedIn/);
  await page.goto('/infernal-drops?catalog='+manifest.id);
  await expect(page.getByRole('heading',{name:'强化生物掉落池',exact:true})).toBeVisible();
  await expect(page.locator('.infernal-pool-item')).toHaveCount(2);
  await expect(page.locator('.infernal-pool-item').first()).toContainText('加载时数量 3');
  await expect(page.locator('.infernal-pool-item').last()).toContainText('条目 2');
  await expect(page.locator('.infernal-policy')).toContainText('1–5 为精英');
  await page.getByRole('button',{name:'超级',exact:true}).click();
  await expect(page.locator('.infernal-pool-item')).toHaveCount(1);
  await expect(page.locator('.infernal-pool-item')).toContainText('原生随机附魔书');
  await page.reload();await expect(page.locator('.infernal-pool-item')).toHaveCount(1);
  await page.getByRole('button',{name:'炼狱',exact:true}).click();
  await expect(page.locator('.infernal-page')).toContainText('该等级原生掉落池为空');
  await page.getByRole('button',{name:'精英',exact:true}).click();
  await expect(page.locator('.infernal-pool-item')).toHaveCount(2);
  await page.screenshot({path:testInfo.outputPath('infernal-drops.png'),fullPage:true});
  await page.locator('.infernal-pool-item .item-link').first().click({button:'right'});
  await expect(page).toHaveURL(/\/recipe\/item_.*tab=usedIn/);
  await page.goto('/draconic-reactor?catalog='+manifest.id);
  await expect(page.getByRole('heading',{name:'龙之进化反应堆',exact:true})).toBeVisible();
  await expect(page.locator('.reactor-page tbody tr')).toHaveCount(7);
  await expect(page.locator('.reactor-page')).toContainText('11664');
  await expect(page.locator('.reactor-rules')).toContainText('严格大于');
  await expect(page.locator('.reactor-rules')).toContainText('手动取出不直接生成完整碎片');
  await page.reload();await expect(page.locator('.reactor-page tbody tr')).toHaveCount(7);
  await page.screenshot({path:testInfo.outputPath('draconic-reactor.png'),fullPage:true});
  await page.locator('.reactor-page .reactor-section').last().scrollIntoViewIfNeeded();
  await page.locator('.workspace-content').evaluate(element=>{element.scrollTop=element.scrollHeight;});
  await expect(page.locator('.reactor-page dd').last()).toBeInViewport();
  expect(await page.locator('.reactor-page dd').last().evaluate(element=>{
    const box=element.getBoundingClientRect();return element.contains(document.elementFromPoint(box.x+box.width/2,box.y+box.height/2));
  })).toBe(true);
  await page.screenshot({path:testInfo.outputPath('reactor-config.png'),fullPage:true});
  await page.locator('.reactor-page .item-link').first().click({button:'right'});
  await expect(page).toHaveURL(/\/recipe\/item_.*tab=usedIn/);
  expect(errors).toEqual([]);
});
